const glyphs = new Map<string, boolean[][]>();
for (const [ch, rows] of Object.entries(G)) {
  glyphs.set(ch, rows.split('|').map((r) => [...r].map((c) => c === '#')));
}

/** Draws `text` with its first glyph cell at (x, y). Unknown characters render blank. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, ink: string): void {
  ctx.fillStyle = ink;
  let cx = x;
  for (const ch of text) {
    const g = glyphs.get(ch);
    if (g) {
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c]) ctx.fillRect(cx + c, y + r, 1, 1);
    }
    cx += 6;
  }
}

export const textWidth = (text: string) => [...text].length * 6;
