// 16×16 LCD sprites, original art. '#' = lit pixel; everything else is transparent.
// Boat and cactus sprites keep their top 2 px empty for the timer bars (rulebook §3).

export type Sprite = boolean[][];

// RG-001: the chopper art was written as 11 rows, and blit() reads all 16 rows of a cell, so the
// first chopper entry threw in the render loop and froze the game. parse() now pads every sprite
// to a full 16×16 cell (blank rows at the bottom), so short art can never be read out of bounds.
const parse = (rows: string[]): Sprite =>
  [...rows, ...Array<string>(Math.max(0, 16 - rows.length)).fill('')]
    .slice(0, 16)
    .map((r) => [...r.padEnd(16, '.')].slice(0, 16).map((c) => c === '#'));
const mirror = (s: Sprite): Sprite => s.map((r) => [...r].reverse());
const shiftDown = (s: Sprite, n: number): Sprite => [...Array(n).fill(Array(16).fill(false)), ...s].slice(0, 16);

/** Outline of a solid sprite: lit pixels with an unlit 4-neighbour (the tutorial boat, L1). */
function outline(s: Sprite): Sprite {
  const at = (r: number, c: number) => r >= 0 && r < 16 && c >= 0 && c < 16 && s[r][c];
  return s.map((row, r) => row.map((on, c) => on && (!at(r - 1, c) || !at(r + 1, c) || !at(r, c - 1) || !at(r, c + 1))));
}

