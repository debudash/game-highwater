// The ghost hint's recordings (src/sim/ghosts.ts) are the stage bots' inputs. This test re-records
// them and fails if the file is stale; regenerate with UPDATE_GHOSTS=1 npx vitest run tests/ghosts.test.ts.
// It also replays each recording from a fresh room to prove the ghost retraces a clean run.
import { describe, expect, it } from 'vitest';
import { readFileSync, writeFileSync } from 'node:fs';
import { createGame, Game, tick } from '../src/sim/game';
import { encodeInputs, ghostInputs } from '../src/sim/ghost';
import { Button, TickInput } from '../src/sim/input';
import { GAME_ROOMS } from '../src/sim/stages';
import { input } from './helpers';
import { STAGE_BOTS } from './stagebots';

function record(i: number): TickInput[] {
  const def = GAME_ROOMS[i];
  const g = createGame({ rooms: GAME_ROOMS, startRoom: i });
  const policy = STAGE_BOTS[def.id]();
  const out: TickInput[] = [];
  let prev = new Set<Button>();
  for (let t = 0; t < 4000 && g.room.index === i && g.loops === 0 && !g.complete; t++) {
    const { held, press = [] } = policy(g, t);
    const fresh = [...new Set([...press, ...held.filter((b) => !prev.has(b))])];
    const inp = input(held, fresh);
    out.push(inp);
    tick(g, inp);
    prev = new Set([...held, ...press]);
  }
  return out;
}

const FILE = 'src/sim/ghosts.ts';

describe('ghost recordings', () => {
  const recorded: Record<string, string> = {};
  GAME_ROOMS.forEach((def, i) => { recorded[def.id] = encodeInputs(record(i)); });
  const body = `// Generated by tests/ghosts.test.ts (UPDATE_GHOSTS=1 npx vitest run tests/ghosts.test.ts). Do not edit.\n`
    + `// Each room's bot solution as run-length-encoded tick inputs (see src/sim/ghost.ts).\n`
    + `export const GHOSTS: Record<string, string> = ${JSON.stringify(recorded, null, 2)};\n`;

  it('match the bots (regenerate with UPDATE_GHOSTS=1)', () => {
    if (process.env.UPDATE_GHOSTS) writeFileSync(FILE, body);
    expect(readFileSync(FILE, 'utf-8')).toBe(body);
  });

  GAME_ROOMS.forEach((def, i) => {
    it(`${def.id}: the recording clears the room from a fresh start`, () => {
      const inputs = ghostInputs(def.id);
      expect(inputs).not.toBeNull();
      // The ghost plays the room alone, as the view does.
      const g: Game = createGame({ rooms: [def], startRoom: 0 });
      for (const inp of inputs!) tick(g, inp);
      expect(g.deaths).toBe(0);
      expect(g.loops).toBe(1);
      void i;
    });
  });
});
